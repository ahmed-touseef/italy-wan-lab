#!/usr/bin/env python3
"""Italy WAN lab generator.

The tables below describe the whole network. Running ./gen.py writes:
  italy.clab.yml         the containerlab topology (devices and cables)
  configs/<router>.conf  FRR config for each router (Cisco style)
  configs/<device>.sh    setup script for each switch and PC
Change a table, run ./deploy.sh, and the lab follows.
"""
from pathlib import Path

FRR_IMAGE = "quay.io/frrouting/frr:10.2.1"
HOST_IMAGE = "italy-host:1"

# name, city number, short code (same numbering as the Packet Tracer lab)
CITIES = [("milan", 1, "mil"), ("turin", 2, "trn"), ("genoa", 3, "gen"),
          ("florence", 4, "flr"), ("rome", 5, "rom"), ("naples", 6, "nap")]
SITES = [1, 2, 3, 4]  # four sites per city, each with one switch and one PC

# Router port for each site, with the Packet Tracer name it replaces
SITE_PORT = {1: ("eth1", "Fa0/0"), 2: ("eth2", "Fa1/0"),
             3: ("eth3", "Fa7/0"), 4: ("eth4", "Fa6/0")}
RING_PT_NAME = {"eth5": "Fa4/0", "eth6": "Fa5/0"}

# The ring, cabled as in Packet Tracer: (city, port, city, port)
RING = [("milan", "eth5", "turin", "eth5"), ("turin", "eth6", "genoa", "eth5"),
        ("genoa", "eth6", "florence", "eth5"), ("florence", "eth6", "rome", "eth5"),
        ("rome", "eth6", "naples", "eth5"), ("naples", "eth6", "milan", "eth6")]

# Remote access: WireGuard tunnel ending on this router (set up by remote-access.sh)
REMOTE = {"router": "milan", "port": "wg0", "room": "10.9.0", "listen": 51821}

NUM = {name: n for name, n, _ in CITIES}


def ring_link(a, b):
    """Room 10.0.XY.0/30 (X, Y = city numbers, low first); the lower city gets .1."""
    lo, hi = sorted((NUM[a], NUM[b]))
    room = f"10.0.{lo}{hi}"
    return room, {c: f"{room}.{1 if NUM[c] == lo else 2}" for c in (a, b)}


def router_conf(name, n):
    out = [
        "frr defaults traditional",
        f"hostname {name}",
        "service integrated-vtysh-config",
        "!",
        f"! Router {name}, generated by gen.py.",
        "! bandwidth 100000 = 100 Mbit/s, like FastEthernet, so every OSPF cost is 1",
        "! exactly as in Packet Tracer.",
        "! Site ports are OSPF passive: their networks are advertised, but no OSPF",
        "! hellos go to or are accepted from the office LANs.",
        "!",
    ]
    for s in SITES:
        port, pt = SITE_PORT[s]
        out += [f"interface {port}",
                f" description site {s} ({pt} in Packet Tracer)",
                f" ip address 10.{n}.{s}.1/24",
                " bandwidth 100000",
                " ip ospf passive",
                "!"]
    ring = []
    for a, pa, b, pb in RING:
        _, ip = ring_link(a, b)
        for me, port, peer in ((a, pa, b), (b, pb, a)):
            if me == name:
                ring.append((port, peer, ip[me]))
    for port, peer, addr in sorted(ring):
        out += [f"interface {port}",
                f" description ring to {peer} ({RING_PT_NAME[port]} in Packet Tracer)",
                f" ip address {addr}/30",
                " bandwidth 100000",
                "!"]
    if name == REMOTE["router"]:
        out += [f"interface {REMOTE['port']}",
                " description WireGuard remote access (created by remote-access.sh)",
                f" ip address {REMOTE['room']}.1/24",
                " ip ospf passive",
                "!"]
    out += ["router ospf",
            f" ospf router-id {n}.{n}.{n}.{n}",
            f" network 10.{n}.0.0/16 area 0",
            " network 10.0.0.0/16 area 0",
            *([f" network {REMOTE['room']}.0/24 area 0"] if name == REMOTE["router"] else []),
            "!",
            "line vty",
            "!"]
    return "\n".join(out) + "\n"


def switch_sh(city, n, code, s):
    return f"""# needs: eth1 eth2
# {code.upper()}{s}SW: {city.capitalize()} site {s} switch (the 2960 in Packet Tracer)
ip link add vlan1 type bridge             # the switch itself: all ports in VLAN 1
ip link set eth1 master vlan1             # uplink to the {city} router
ip link set eth2 master vlan1             # port to {code}{s}pc
ip link set eth1 up
ip link set eth2 up
ip link set vlan1 up
ip addr add 10.{n}.{s}.7/24 dev vlan1       # interface vlan 1 + ip address
ip route replace default via 10.{n}.{s}.1   # ip default-gateway
"""


def pc_sh(city, n, code, s):
    return f"""# needs: eth1
# {code.upper()}{s}PC: {city.capitalize()} site {s} PC
# Packet Tracer: ipconfig 10.{n}.{s}.2 255.255.255.0 10.{n}.{s}.1
ip link set eth1 up
ip addr add 10.{n}.{s}.2/24 dev eth1
ip route replace default via 10.{n}.{s}.1 dev eth1
"""


DAEMONS = """bgpd=no
ospfd=yes
ospf6d=no
ripd=no
ripngd=no
isisd=no
pimd=no
ldpd=no
nhrpd=no
eigrpd=no
babeld=no
sharpd=no
pbrd=no
bfdd=no
fabricd=no
vrrpd=no
pathd=no
vtysh_enable=yes
zebra_options="  -A 127.0.0.1 -s 90000000"
mgmtd_options="  -A 127.0.0.1"
ospfd_options="  -A 127.0.0.1"
staticd_options="-A 127.0.0.1"
"""


def main():
    root = Path(__file__).resolve().parent
    cfg = root / "configs"
    cfg.mkdir(exist_ok=True)
    (cfg / "daemons").write_text(DAEMONS)
    (cfg / "vtysh.conf").write_text("service integrated-vtysh-config\n")

    nodes, links = [], []
    for a, pa, b, pb in RING:
        room, _ = ring_link(a, b)
        links.append(f'    - endpoints: ["{a}:{pa}", "{b}:{pb}"]   # {room}.0/30')

    for city, n, code in CITIES:
        (cfg / f"{city}.conf").write_text(router_conf(city, n))
        nodes += [f"    {city}:",
                  f"      image: {FRR_IMAGE}",
                  f"      binds: [configs/{city}.conf:/etc/frr/frr.conf, configs/daemons:/etc/frr/daemons, configs/vtysh.conf:/etc/frr/vtysh.conf]",
                  "      exec:",
                  "        - sysctl -w net.ipv4.ip_forward=1"]
        for s in SITES:
            sw, pc = f"{code}{s}sw", f"{code}{s}pc"
            (cfg / f"{sw}.sh").write_text(switch_sh(city, n, code, s))
            (cfg / f"{pc}.sh").write_text(pc_sh(city, n, code, s))
            for dev in (sw, pc):
                nodes += [f"    {dev}:",
                          f"      image: {HOST_IMAGE}",
                          f"      binds: [configs/{dev}.sh:/config.sh:ro]"]
            port = SITE_PORT[s][0]
            links.append(f'    - endpoints: ["{city}:{port}", "{sw}:eth1"]   # 10.{n}.{s}.0/24')
            links.append(f'    - endpoints: ["{sw}:eth2", "{pc}:eth1"]')

    topo = "\n".join([
        "# Italy WAN lab topology. Generated by gen.py: edit gen.py, not this file.",
        "name: italy",
        "",
        "mgmt:",
        "  network: italy-mgmt",
        "  ipv4-subnet: 172.30.40.0/24",
        "  ipv6-subnet: 3fff:172:30:40::/64",
        "",
        "topology:",
        "  defaults:",
        "    kind: linux",
        "  nodes:",
        *nodes,
        "",
        "  links:",
        *links,
    ]) + "\n"
    (root / "italy.clab.yml").write_text(topo)
    print(f"Generated italy.clab.yml: {len(CITIES)} routers, "
          f"{len(CITIES) * len(SITES)} switches, {len(CITIES) * len(SITES)} PCs, "
          f"{len(links)} cables")


if __name__ == "__main__":
    main()
